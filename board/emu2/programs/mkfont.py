def col_bytes(ch):
    rows = G.get(ch, G['?']).split('/')
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    return [sum(1 << y for y in range(7) if rows[y][x] == '#') for x in range(5)]

if __name__ == "__main__":
    out = ["; generated by mkfont.py: 5 columns per glyph, bit 0 = top row; ASCII 32..95 (lower case maps to upper)",
           ".data", "font:"]
    for c in range(32, 96):
        out.append("        .byte " + ",".join("0x%02X" % b for b in col_bytes(chr(c))) + "   ; '%s'" % chr(c))
    open("lib/font5x7.inc", "w").write("\n".join(out) + "\n.code\n")
